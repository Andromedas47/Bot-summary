-- Produce Product Code Dictionary — an optional short code for a product name.
--
-- Operators key product names by hand, so one physical product accumulates many
-- spellings (กล้วยน้ำว้า / กล้วยน้ำหว้า / น้ำว้า / กล้วหว้า) and every downstream
-- comparison — เบิก vs ชั่งคืน, price, unit, quantity invariant, reconciliation,
-- the 08:00 report — has to reconcile identities that were never really equal.
-- A short code (ม02 = กล้วยน้ำว้า) removes the keying variance at the source.
--
-- What this table is NOT: an allowlist. A product absent from it is still a
-- perfectly valid product, entered as ordinary text exactly as before, and the
-- many products deliberately excluded from this first dictionary are excluded
-- from *codes*, not from the shop. Nothing in this migration can refuse a
-- product; resolution happens in the parser and only ever turns a registered
-- code into the product name it stands for.
--
-- Additive and historical-safe. One new table, one seed of 253 approved rows.
-- No UPDATE and no DELETE against any existing table: produce_transactions,
-- produce_sessions, produce_items, accountability_rounds and the 2026-08-11
-- history are not read, not rewritten and not backfilled here.
--
-- Deliberately NOT reusing purchase_intake_product_registry: that table is P2B
-- purchase-capture's raw-text → product_key normalization (§10.3), owned by a
-- different ingestion path, with its own no-delete identity trigger and its own
-- normalization CHECK. Produce code resolution has different semantics (a code
-- is not a spelling of the name) and pointing produce at it would couple two
-- ingestion systems that have no reason to move together.
BEGIN;

CREATE TABLE IF NOT EXISTS public.produce_product_codes (
  product_code   text        PRIMARY KEY
                             CHECK (product_code ~ '^[มผปทหพ][0-9]{1,4}$'),
  category_code  text        NOT NULL CHECK (category_code ~ '^[มผปทหพ]$'),
  category_name  text        NOT NULL CHECK (length(btrim(category_name)) > 0),
  canonical_name text        NOT NULL CHECK (length(btrim(canonical_name)) > 0),
  -- false = this code stops resolving and fails closed like an unregistered
  -- one. It never means the product itself is retired: canonical_name stays
  -- enterable as ordinary text, exactly as it was before it had a code.
  code_enabled   boolean     NOT NULL DEFAULT true,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT produce_product_codes_category_prefix
    CHECK (left(product_code, 1) = category_code)
);

COMMENT ON TABLE public.produce_product_codes IS
  'Optional short code → canonical produce product name. Identification only, '
  'never an allowlist: an uncoded product remains fully enterable as text.';
COMMENT ON COLUMN public.produce_product_codes.code_enabled IS
  'false = the code no longer resolves (fails closed). The product name itself '
  'stays valid. Rows are never deleted, so a code is never reissued.';

CREATE INDEX IF NOT EXISTS produce_product_codes_category_idx
  ON public.produce_product_codes (category_code);
CREATE INDEX IF NOT EXISTS produce_product_codes_canonical_name_idx
  ON public.produce_product_codes (canonical_name);

-- Code stability (§6): a released code is permanent. It may be disabled, but it
-- may never be deleted, renumbered, or repointed at a different product — that
-- would silently rewrite the identity of every transaction already keyed by it.
CREATE OR REPLACE FUNCTION public.produce_product_codes_forbid_identity_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'produce_product_codes rows must not be deleted (code % is permanent)',
      OLD.product_code;
  END IF;

  IF NEW.product_code IS DISTINCT FROM OLD.product_code
     OR NEW.canonical_name IS DISTINCT FROM OLD.canonical_name
     OR NEW.category_code IS DISTINCT FROM OLD.category_code THEN
    RAISE EXCEPTION
      'produce_product_codes identity is immutable (code %): disable it with code_enabled instead',
      OLD.product_code;
  END IF;

  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS produce_product_codes_identity_guard ON public.produce_product_codes;
CREATE TRIGGER produce_product_codes_identity_guard
  BEFORE UPDATE OR DELETE ON public.produce_product_codes
  FOR EACH ROW EXECUTE FUNCTION public.produce_product_codes_forbid_identity_mutation();

ALTER TABLE public.produce_product_codes ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.produce_product_codes FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.produce_product_codes TO service_role;

